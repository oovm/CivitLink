use gg_core::GResult;

/// 移动平台生命周期管理 trait
///
/// 定义移动平台（iOS/Android）的应用生命周期回调。
/// 移动应用需要处理暂停、恢复、销毁等系统事件，
/// 以正确保存和恢复游戏状态。
pub trait MobileLifecycle {
    /// 应用被暂停时调用
    ///
    /// 当应用进入后台（如用户切换到其他应用、接听电话等）时触发。
    /// 应在此保存游戏状态，释放非必要资源。
    fn on_pause(&mut self) -> GResult<()>;

    /// 应用被恢复时调用
    ///
    /// 当应用从后台返回前台时触发。
    /// 应在此恢复游戏状态，重新加载必要资源。
    fn on_resume(&mut self) -> GResult<()>;

    /// 应用被销毁时调用
    ///
    /// 当系统回收应用资源或用户主动关闭应用时触发。
    /// 应在此执行最终清理和持久化操作。
    fn on_destroy(&mut self) -> GResult<()>;
}
